const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');

// Drift guard: everything under src/proto is VENDORED (copied) from the shared
// @runanywhere/proto-ts package because @runanywhere/electron is standalone and
// can't consume the workspace package. If an idl/*.proto evolves, the shared
// source is regenerated but the vendored copy would silently diverge. These
// tests fail loudly on drift so the copies are kept in sync (re-copy the shared
// file). F21 replaces vendoring with the workspace dependency and deletes them.
const VENDOR_DIR = path.join(__dirname, '..', '..', 'src', 'proto');
const SHARED_DIR = path.join(__dirname, '..', '..', '..', 'shared', 'proto-ts', 'src');
const MARKER = '// Code generated by protoc-gen-ts_proto';

// The shared package lives elsewhere in the monorepo; skip when this is a
// partial checkout (e.g. the SDK extracted on its own).
const SHARED_PRESENT = fs.existsSync(SHARED_DIR);
const VENDORED = fs.readdirSync(VENDOR_DIR).filter((f) => f.endsWith('.ts')).sort();

/** Generated body after the vendored header (line-ending + trailing-ws normalized). */
function generatedBody(file) {
  const src = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const i = src.indexOf(MARKER);
  assert.ok(i >= 0, `${file} is missing the protoc-gen-ts_proto marker`);
  return src.slice(i).trimEnd();
}

test('there is something vendored to check', () => {
  assert.ok(VENDORED.length > 0, 'src/proto is empty');
});

for (const name of VENDORED) {
  test(`vendored src/proto/${name} matches the shared proto-ts source (no drift)`, { skip: !SHARED_PRESENT }, () => {
    const shared = path.join(SHARED_DIR, name);
    assert.ok(fs.existsSync(shared), `src/proto/${name} has no counterpart at ${shared}`);
    assert.equal(
      generatedBody(path.join(VENDOR_DIR, name)),
      generatedBody(shared),
      `src/proto/${name} has drifted from sdk/shared/proto-ts/src/${name} — re-copy the shared file (keep only the vendored header).`
    );
  });

  test(`src/proto/${name} carries a provenance header explaining why it is copied`, () => {
    const head = fs.readFileSync(path.join(VENDOR_DIR, name), 'utf8').slice(0, 600);
    assert.match(head, /VENDORED from @runanywhere\/proto-ts/);
  });
}
