#!/usr/bin/env python3
"""Fail when the hand-written RN Hybrid header drifts from the generated Nitro spec.

`HybridRunAnywhereCore.hpp` is hand-written; `HybridRunAnywhereCoreSpec.hpp` is
generated by nitrogen from `*.nitro.ts`. Changing a spec method's signature
regenerates the pure virtual but does NOT touch the hand-written override, so the
two silently disagree and the C++ stops compiling.

PR CI never caught that: `rn-typecheck` only type-checks TypeScript, and the RN
C++ is compiled solely by an app build (CocoaPods / Gradle), which PR CI does not
run. This gate is the cheap stand-in — it compares return types per method name.

Exit 0 when in sync, 1 otherwise.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
CORE = REPO / "sdk/runanywhere-react-native/packages/core"
SPEC = CORE / "nitrogen/generated/shared/c++/HybridRunAnywhereCoreSpec.hpp"
IMPL = CORE / "cpp/HybridRunAnywhereCore.hpp"

COMMENT_RE = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)
# Trailing `<ret...> <name>(` of a declaration, once comments are gone.
SIGNATURE_RE = re.compile(r"^(?P<ret>.*?)\b(?P<name>\w+)\s*\($", re.S)


def strip_comments(text: str) -> str:
    return COMMENT_RE.sub(" ", text)


def declarations(text: str, marker: str) -> dict[str, str]:
    """Map method name -> normalized return type for statements containing `marker`.

    Splitting on ';' is what makes this robust: every C++ declaration ends with
    one, so wrapped signatures rejoin naturally and prose can't be mistaken for a
    declaration (it would have to end in `) override;`).
    """
    found: dict[str, str] = {}
    for statement in strip_comments(text).split(";"):
        if marker not in statement:
            continue
        # Keep only the part before the argument list.
        head, sep, _ = statement.partition("(")
        if not sep:
            continue
        match = SIGNATURE_RE.match(head.strip() + "(")
        if not match:
            continue
        ret = re.sub(r"\s+", " ", match.group("ret")).strip()
        # The first declaration in a class carries the preamble ("class X {
        # public:") into `ret`; keep only what follows the last brace or access
        # specifier.
        for boundary in ("{", "}", "public:", "private:", "protected:"):
            if boundary in ret:
                ret = ret.rsplit(boundary, 1)[1]
        ret = ret.strip()
        # Drop leading specifiers so the two sides are comparable.
        for kw in ("virtual", "explicit", "static", "inline"):
            if ret.startswith(kw + " "):
                ret = ret[len(kw) + 1:]
        ret = ret.replace("& ", "&").replace(" &", "&").strip()
        if ret:
            found[match.group("name")] = ret
    return found


def main() -> int:
    for path in (SPEC, IMPL):
        if not path.exists():
            print(f"::error::missing {path.relative_to(REPO)}")
            return 1

    spec = declarations(SPEC.read_text(), "= 0")
    impl = declarations(IMPL.read_text(), "override")

    if len(spec) < 20:
        print(f"::error::parsed only {len(spec)} spec methods — this gate's parser is broken")
        return 1

    problems: list[str] = []
    for name, ret in sorted(spec.items()):
        if name not in impl:
            problems.append(f"  {name}: in the spec, missing from the hand-written header")
        elif impl[name] != ret:
            problems.append(f"  {name}: spec returns '{ret}', header declares '{impl[name]}'")

    if problems:
        print("::error::HybridRunAnywhereCore.hpp is out of sync with the generated Nitro spec")
        print("\n".join(problems))
        print("\nRegenerate with `yarn core:nitrogen`, then update cpp/HybridRunAnywhereCore.hpp to match.")
        return 1

    print(f"nitro spec/header in sync ({len(spec)} methods)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
